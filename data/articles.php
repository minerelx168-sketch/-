## KRA IMEI Declaration vs. CA Device Registration

These are two separate but linked processes:

| Process | Managed By | When Required | Purpose |
|---|---|---|---|
| **F88 IMEI Declaration** | KRA (Customs) | On arrival at port of entry | Customs duty compliance |
| **CA Device Registration** | Communications Authority | Within 90 days of connecting to a Kenyan network | Network access authorization |

If you declare at customs (F88), your data is automatically fed to the CA system. However, **Kenyan residents who purchased phones locally** and never went through customs still need to register directly with the CA if their device was not part of an authorized import batch.


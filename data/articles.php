## Red Flags to Watch For in Lagos & Abuja Markets

After speaking with phone traders and NCC investigators, these are the most common tactics used to sell blacklisted phones in Nigerian markets:

### 1. The "Overseas Phone" Story
Sellers claim the phone "just arrived from the UK/USA/Dubai." Many imported phones were reported stolen in their home country and are on international blacklists. **Always check before buying.**

### 2. Mismatched IMEI Numbers
On dual-SIM phones, there are two IMEI numbers. Check **both**. A legitimate device will have both IMEIs registered to the same model. If IMEI 1 checks out but IMEI 2 returns unknown or a different model, the device may have a cloned or patched firmware.

### 3. Unusually Low Prices
An iPhone 15 selling for ₦150,000 when the market rate is ₦500,000+ is a major red flag. Blacklisted phones are sold at heavy discounts because they will eventually stop working on Nigerian networks.

### 4. Pressure to "Buy Now Before It's Gone"
This classic high-pressure tactic is designed to prevent you from doing your due diligence. Always insist on checking the IMEI *before* paying. A legitimate seller will have no objection.

### 5. Scratched or Altered IMEI Sticker
Physically inspect the SIM tray and back of the device. A scratched, reprinted, or clearly replaced IMEI sticker suggests the original was tampered with.


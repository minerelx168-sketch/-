## KRA F88 Form: How to Register Your IMEI at Kenyan Airports

If you're **arriving in Kenya** with a smartphone purchased abroad, you are legally required to declare it using the **KRA F88 Customs Declaration Form**. Here's the step-by-step process:

### Step 1: Prepare Your Documents
Gather the following before you land at JKIA, Moi International Airport (Mombasa), or any other port of entry:
- Your passport or national ID
- The phone's original box (if available) with IMEI label
- Purchase receipt or invoice showing the phone's value in USD
- Your phone with the IMEI visible on-screen (`*#06#`)

### Step 2: Proceed to KRA Customs at the Airport
After clearing immigration, proceed to the **KRA Customs Desk** (Red Channel) if:
- You are carrying a phone worth more than **USD 500 (approx. KES 65,000)**
- You are carrying **more than two smartphones**
- You purchased the phone abroad within the last 30 days

### Step 3: Complete the F88 Form
The F88 form requires:
- Full name and passport/ID number
- Device description (brand, model, storage size)
- **IMEI number(s)** — this is mandatory
- Declared purchase value
- Reason for import (personal use, gift, resale)

### Step 4: Pay Import Duty (If Applicable)
KRA calculates duty based on the **CIF value** (Cost + Insurance + Freight) of the device:

| Device Value (USD) | Import Duty Rate | VAT (16%) | Approximate Total Tax |
|---|---|---|---|
| Under $500 | 0% (personal exemption) | 0% | KES 0 |
| $500 – $1,000 | 25% customs duty | 16% on total | ~KES 28,000 – 60,000 |
| Over $1,000 | 25% customs duty | 16% on total | ~KES 60,000+ |

> **Pro Tip:** Keep your purchase receipt. KRA officers use the receipt value, not the market value, to calculate your duty. A clear receipt from the original retailer can save you thousands of shillings.

### Step 5: Receive Your IMEI Registration Certificate
After payment (if applicable), KRA issues a **registration receipt** with your IMEI number stamped. Keep this document — you may need it if your phone is ever queried by network operators or law enforcement.


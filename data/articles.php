## Who Must Declare Their Phone?

You must complete the F88 IMEI declaration if you are:

- A **foreign tourist** carrying a smartphone not previously registered in Kenya
- A **Kenyan resident returning** from abroad with a new phone purchased overseas
- A **business traveler** carrying multiple devices
- Anyone carrying a phone **purchased within the last 12 months** outside Kenya

**You do NOT need to declare** if:

- The phone is already registered in the CA/CEIR Kenya database from a previous visit
- You are in transit through Kenya (less than 24-hour layover) and not connecting to a local SIM


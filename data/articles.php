## Dual-SIM Phones: Register Both IMEIs

A dual-SIM device carries **two separate IMEI numbers** — IMEI 1 for slot 1, IMEI 2 for slot 2. Both must be individually registered on ceir.gov.mm.

- Dial `*#06#` — your phone will display both IMEIs on screen
- Register **each IMEI separately** using the same account
- If only IMEI 1 is registered, SIM slot 2 will be blocked even if slot 1 works

This is one of the most common mistakes seen at PTD service centres — the device appears "half-working" and users assume a hardware fault.


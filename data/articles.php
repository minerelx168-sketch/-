4. **FBR agent verifies** the IMEI against the DIRBS system and calculates your tax based on the current FBR valuation list.
5. **Pay the tax** — cash (PKR) is safest; card terminals are available at major airports but can be slow.
6. **Receive a printed registration receipt** — this is your proof of legal import. Keep it permanently.
7. **Insert your Pakistani SIM** any time after clearing customs. The IMEI is now whitelisted.

**Pro tip:** Airport registration is immediate — you walk out with a fully working phone. Online registration takes 1–3 business days.


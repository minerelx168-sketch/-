## What Is KRA IMEI Declaration?

The Kenya Revenue Authority (KRA) — the government body responsible for customs and excise — introduced compulsory IMEI declaration as part of Kenya's broader **Device Management System (DMS)**, operated in conjunction with the **Communications Authority of Kenya (CA)**. The goal is to:

- **Eliminate counterfeit and stolen phones** from Kenyan networks
- **Enforce import duties** on high-value devices brought into the country
- **Build a national CEIR database** (Central Equipment Identity Register) of all active devices

Every mobile phone has a unique 15-digit IMEI number. When you declare your device at the border, KRA cross-references that IMEI against international blacklists and calculates any applicable import duty.

> **Key fact:** Kenya's CEIR database went live in 2023 and was fully enforced from January 2025. Undeclared phones that connect to Kenyan networks are flagged automatically and scheduled for blocking.


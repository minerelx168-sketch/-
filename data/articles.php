## Penalties for Non-Declaration

Failure to declare a phone on the F88 form — or carrying an unregistered device — carries serious consequences under the Kenya Customs and Excise Act:

| Violation | Consequence |
|---|---|
| Undeclared device detected at customs | Device confiscated; fine up to 200% of import duty owed |
| Undeclared phone connecting to network | IMEI flagged in CEIR; network block within 90 days |
| Providing false IMEI on F88 | Prosecution under the Kenya Information and Communications Act |
| Carrying a blacklisted IMEI | Immediate confiscation; police referral |

Kenyan mobile operators — **Safaricom**, **Airtel Kenya**, and **Telkom Kenya** — are legally required to block SIM cards inserted into devices with unregistered or blacklisted IMEIs.


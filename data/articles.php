### Senegal — ARCEP Sénégal

Senegal's ARCEP (Autorité de Régulation des Télécommunications et des Postes) is one of the more technically advanced regulatory bodies in francophone West Africa. Senegal's IMEI management operates through the national CEIR, with Orange Sénégal, Free Sénégal, and Expresso Sénégal as the principal operators. ARCEP Sénégal has published consumer guidance on IMEI verification and has worked toward harmonising its framework with other UEMOA member states.


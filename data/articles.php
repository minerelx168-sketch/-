## What Exactly Happens When Your Phone Is Blocked

A CEIR block is not a SIM block. It targets the **hardware identifier (IMEI)**, not your phone number. This means:

- **No outgoing or incoming calls** — the device cannot place or receive any call
- **No SMS** — 2FA codes, bank OTPs, and verification texts stop arriving
- **No mobile data** — SIM-based internet access is severed entirely
- **All four operators block simultaneously** — inserting a different SIM does NOT restore service
- **Emergency calls** may also be restricted depending on operator policy
- **Wi-Fi is unaffected** — your phone still works on wireless networks

The key distinction: **the SIM still shows "registered"** on your screen. Bars may even appear. But no traffic flows. Users often assume a network outage or SIM fault before realising the IMEI is the cause.


## The 60-Day Traveller Grace Period — Know Your Rights

PTA grants a **60-day tax-free operational window** for all newly imported devices. During this period:

- Your phone works normally on all Pakistani networks
- You are expected to complete registration and pay the applicable tax before expiry

If you are a **non-resident visiting Pakistan for fewer than 60 days**, your device may qualify for temporary use without full registration — but using a Pakistani SIM starts the DIRBS clock. The 60-day countdown begins from the **first network activation**.


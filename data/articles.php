### Step 1 — Gather Your Documents
- **NRC (National Registration Card)** for Myanmar citizens; valid **passport** for foreigners
- **Original purchase receipt** or customs import declaration
- **IMEI number** — from the box label, device back sticker, or `*#06#`
- Phone brand, model name, and manufacture year

### Step 2 — Open ceir.gov.mm
- Navigate to **ceir.gov.mm** on any browser
- Select **"Register Device"** (ကိရိယာမှတ်ပုံတင်ရန်)
- Log in with your phone number or create a new account

### Step 3 — Submit Your IMEI Details
- Enter the **15-digit IMEI** exactly as displayed — no spaces or dashes
- Fill in device make, model, and production year
- Upload a clear photo of your **receipt or import document**
- Hit Submit — you will receive an **SMS acknowledgement** within hours

### Step 4 — Confirm Registration Status
- Return to ceir.gov.mm after **1–3 business days**
- Check your IMEI status — it should now show **"Compliant"**
- Screenshot or save your **confirmation reference number**


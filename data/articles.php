## What Is the F88 Form?

The **F88 Traveller's Declaration Form** is the official KRA customs document that all international passengers must complete on arrival at:

- **Jomo Kenyatta International Airport (JKIA)**, Nairobi
- **Moi International Airport**, Mombasa
- **Kisumu International Airport**
- All other gazetted ports of entry (road and sea)

### What the F88 Form Requires for Phones

| Field | What to Enter |
|---|---|
| Item Description | Make and model (e.g., "Apple iPhone 15 Pro") |
| IMEI Number | Your device's 15-digit IMEI (`*#06#` to find it) |
| Country of Purchase | Where you originally bought the phone |
| Estimated Value (USD) | Declared market value of the device |
| Quantity | Number of phones being declared |

Phones **valued below KES 50,000 (approx. USD 385)** are typically exempt from import duty for personal use (one device per traveler). Phones above this threshold may attract a **16% VAT** and a **25% Import Duty**, calculated by KRA customs officers.


## How to Register Your Phone and Pay PTA Tax

### For Travellers — Passport-Based Registration

Travellers bringing phones into Pakistan for personal use can register up to **5 devices per calendar year** using their passport — the most common method for overseas Pakistanis visiting family.

**Step 1 — Register before the 60-day window closes**
Visit **id.pta.gov.pk** and click **"DIRBS Traveller Registration."**

**Step 2 — Sign in or create a PTA account**
Use your passport number and a valid mobile number (a foreign number works for initial account creation).

**Step 3 — Enter your device details**
Provide IMEI number(s), phone brand and model, and an estimated value.

**Step 4 — Receive your tax assessment**
PTA's system calculates the applicable registration tax and displays payment instructions.

**Step 5 — Pay via banking or mobile wallet**
Accepted payment methods:
- Pakistani bank internet transfer
- **Easypaisa** or **JazzCash** mobile wallets
- Over-the-counter at designated bank branches (HBL, UBL, MCB, Allied Bank)

**Step 6 — Confirmation**
After payment, your IMEI is registered in DIRBS and shows as "Compliant" within **24–48 hours**.

### For Pakistani Residents — CNIC-Based Registration

Residents with a **CNIC (Computerized National Identity Card)** can register devices via the PTA DIRBS portal using their CNIC number. The process mirrors the traveller route but uses CNIC instead of passport. NADRA's verification system is integrated for real-time identity confirmation.


## What Is an IMEI Number and Why Does It Matter in Kenya?

Your **IMEI (International Mobile Equipment Identity)** is a unique 15-digit number that identifies your specific device on cellular networks. Think of it as your phone's national ID card.

In Kenya, the IMEI matters for three critical reasons:

1. **KRA Tax Compliance** – Phones brought into Kenya from abroad must be declared using the KRA **F88 Form**. The IMEI is how customs officers verify the device's identity and calculate import duties.

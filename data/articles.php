## How to Unblock a Previously Blocked Phone

If your device is already blocked, registration alone does not instantly restore service. You must also file an unblock request:

1. **Complete CEIR registration** (steps above) — you cannot unblock without it
2. **Contact your operator's service center** with your CEIR confirmation:
   - **MPT** — visit any MPT branch; bring NRC and CEIR reference
   - **Mytel** — call toll-free **1800** or visit a Mytel Experience Center
   - **Ooredoo** — call **1333** or submit via myooredoo.com.mm
   - **Telenor** — visit telenor.com.mm/support or a Telenor shop
3. **Provide CEIR registration proof** — the SMS confirmation or portal screenshot
4. Allow **3–7 business days** for the block to lift across all networks

**Warning:** Street vendors in electronics markets offering "IMEI unlock" services without CEIR registration are running illegal operations. The block exists at the network infrastructure level — no software tool or code entry can bypass it.


## What to Do If You Already Bought a Blacklisted Phone

If you discover — after purchase — that your phone is blacklisted, here are your options:

1. **Return to the seller immediately.** Under Nigerian consumer protection law (FCCPC Act), selling a stolen or defective product is illegal. Document everything and demand a refund.

2. **Report to the FCCPC.** The Federal Competition and Consumer Protection Commission handles consumer complaints. File at **fccpc.gov.ng**.

3. **Report to the NCC.** The NCC can flag the seller's IMEI supply chain for investigation. Contact them at **ncc.gov.ng/consumer-protection**.

4. **File a police report.** If the phone was stolen property, filing a report with the Nigeria Police Force protects you legally as an innocent buyer.

5. **Do not attempt to "unlock" or "re-flash" the IMEI.** Modifying an IMEI is a federal offence in Nigeria under the Nigerian Communications Act 2003. The penalty can include imprisonment.


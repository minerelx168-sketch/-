**Solution:** IMEI cloning is illegal in Kenya under the Kenya Information and Communications Act. If you discover your IMEI is duplicated, report to the CA immediately and your device will need to be replaced — the manufacturer (not KRA) issues replacement IMEIs through authorized service centers.


## What is an IMEI Number?

IMEI stands for **International Mobile Equipment Identity**. It is a unique 15-digit serial number assigned to every mobile phone at the factory. No two phones should ever share the same IMEI — which is why cloned IMEIs are a red flag for fraud.

**How to find your IMEI:**

- Dial `*#06#` on any phone — the IMEI appears on screen instantly
- Check **Settings → About Phone → IMEI** on Android
- Check **Settings → General → About** on iPhone
- Look on the **SIM card tray** (printed on most iPhones and Samsung flagships)
- Check the **original box** or the sticker inside the back cover

> **Pro Tip:** A legitimate phone will show the **same IMEI** across all three methods. If the IMEI in Settings does not match `*#06#`, the device firmware may have been tampered with — a major warning sign.


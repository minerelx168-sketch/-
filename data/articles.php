## Frequently Asked Questions

**My phone is blocked by PTA — can it be unblocked?**
A phone blocked after the 60-day period generally cannot be unblocked without paying the full registration tax plus potential late penalties. Contact the PTA helpline at **0800-55055** or visit pta.gov.pk/dirbs for case-specific guidance.

**Does DIRBS block both SIM slots on a dual-SIM phone?**
Yes. When an IMEI is blocked, neither SIM slot in that handset can connect to any Pakistani network.

**What if the DIRBS website shows my registered phone as blocked?**
Processing delays can occur. Wait 48–72 hours after payment confirmation. If the status has not updated, call the PTA helpline at 0800-55055 with your payment receipt ready.

**Do phones manufactured or assembled in Pakistan require DIRBS registration?**
No. Phones produced by PTA-licensed local manufacturers are pre-enrolled in DIRBS. You do not need to register them separately.

**I ordered a phone on Amazon and shipped it to Pakistan via a courier — does the traveller exemption apply?**
No. Courier shipments are classified as commercial imports, not personal baggage. They require full customs clearance through the Federal Board of Revenue and standard PTA registration. The 60-day traveller grace period does not apply.

**I am permanently leaving Pakistan — do I need to deregister my phones?**
There is no formal deregistration process. If you sell a PTA-registered phone internationally, the IMEI remains in DIRBS as "Compliant" — this is not an issue for buyers in other countries.

**How do I check multiple IMEIs at once?**
PTA's website handles one IMEI at a time. For bulk IMEI validation, use an IMEI service with API access such as those available at [imeihub.net](https://imeihub.net/).

**What is the PTA helpline number?**
Reach PTA's consumer helpline at **0800-55055** (toll-free from Pakistani networks) or submit an online complaint at pta.gov.pk.

## What Is CEIR and Why Does Myanmar Enforce It?

The CEIR (Central Equipment Identity Register) at **ceir.gov.mm** is a national database of every legitimate mobile device operating inside Myanmar. Managed by the PTD, it was built to:

- Block **counterfeit and substandard handsets** from the market
- Enable tracking of **stolen devices** reported by victims
- Ensure all phones meet Myanmar's **telecommunications standards**
- Cut off devices used in **telecom fraud and scam operations**

Every 15-digit IMEI number on every phone used inside Myanmar must be present in this database. If it is not, Myanmar's four major operators — **MPT, Mytel, Ooredoo, and Telenor** — receive a block order at the network level.


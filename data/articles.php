## Frequently Asked Questions

**Q: Can I bring two phones to Kenya without paying duty?**
A: KRA allows one personal-use phone duty-free per traveler. A second device may attract duty if its combined value with the first exceeds the exemption threshold.

**Q: Does my phone need to be new to require declaration?**
A: No. Any phone that has not previously been registered in Kenya's CEIR database must be declared — whether new or used.

**Q: What if I forget to fill the F88 form on the plane?**
A: Forms are available at the customs desk in the arrivals hall. Do not exit through the green channel without declaring your phone — if caught, the penalties are significantly higher.

**Q: My phone is already registered in another country's CEIR. Do I still need to declare?**
A: Yes. Each country maintains its own CEIR. Registration in another national database does not exempt you from Kenya's declaration requirement.

**Q: How long does the CEIR registration take to reflect?**
A: Typically 24–72 hours after customs processing. If your phone is still showing as unregistered after 5 business days, contact KRA at `customs@kra.go.ke` with your F88 receipt number.


## How PTA Calculates the Tax: The Formula

PTA and FBR use the following multi-layer calculation on phones declared as personal baggage:

1. **Assessable Value (AV)** = USD price × FBR daily exchange rate
2. **Customs Duty (CD)** = 20% of AV *(for phones above USD 500)*
3. **Sales Tax (ST)** = 17% of (AV + CD)
4. **Additional Customs Duty (ACD)** = 4% of AV
5. **Withholding Tax (WHT)** = 6% of (AV + CD + ACD) *(for filers)* / 9% *(for non-filers)*
6. **Total Tax** = CD + ST + ACD + WHT


## What Happens If Your Phone Has an Unregistered IMEI in Kenya?

Under the Kenya Information and Communications (Amendment) Act 2023, Communications Authority of Kenya (CA) has the power to direct network operators to **block devices with unregistered or duplicate IMEIs**. Here's what can happen:

- **Immediate SIM Lock** – Your SIM may stop working even if the SIM card itself is valid
- **Device Blacklisting** – Your phone is added to the national IMEI blacklist, making it unusable on any Kenyan network
- **Customs Penalty** – For undeclared imports, KRA can impose fines of **3x the import duty owed**, plus the original duty
- **Confiscation** – In serious cases (commercial quantities), devices can be seized at the border


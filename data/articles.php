## What Is PTA DIRBS and Why Does It Affect Your iPhone?

The **Pakistan Telecommunication Authority (PTA)** operates the **Device Identification, Registration, and Blocking System (DIRBS)**. Since 2019, every mobile device used on a Pakistani network must be registered in DIRBS. Unregistered phones are flagged and blocked — meaning no calls, no SMS, and no mobile data on any local SIM.

**Key rules for imported iPhones (2025):**

- Phones brought as **personal baggage** must be registered within **60 days** of arrival.
